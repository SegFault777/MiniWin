"""Generates kernel/cursor_data.h: the mouse cursor shapes, from the MiniWin icon pack's Images/Cursor/*.png
(third_party/icon-bundle/, CC BY-SA 4.0, by SegFault777).

Each PNG is a tiny two-colour image with transparency: black outline, white fill. The header holds them as rows of characters
('.' transparent, 'A' outline, 'B' fill) -- the same pixel-art-as-strings form kernel/ui/cursor.h has always drawn, now with
the second colour that makes a pointer visible on any background. The result is art data derived from CC BY-SA 4.0 material, so
the generated header carries that license (not the project's GPL line) and says so.

    tools/gen_cursors.py            rewrite kernel/cursor_data.h
    tools/gen_cursors.py --check    exit 1 if the checked-in header is out of date (used by tools/test/run_host_font.sh)
"""
import os
import sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "third_party", "icon-bundle", "Images", "Cursor")
OUT = os.path.join(ROOT, "kernel", "cursor_data.h")
# (C name, PNG file). The "classic" set; a different style would be another set of files with the same shape names.
SHAPES = [
    ("arrow",    "cursor_arrow_classic.png"),
    ("hresize",  "cursor_horizontal_classic.png"),
    ("vresize",  "cursor_vertical_classic.png"),
    ("diag_nwse", "cursor_diagonal_nwse_classic.png"),
    ("diag_nesw", "cursor_diagonal_nesw_classic.png"),
]


def rows_of(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    colors = {}
    rows = []
    for y in range(h):
        r = ""
        for x in range(w):
            px = im.getpixel((x, y))
            if px[3] == 0:
                r += "."
            elif px[3] != 255:
                sys.exit(f"{path}: partially transparent pixel at ({x},{y}) -- cursors are 1-bit alpha, no anti-aliasing")
            elif px[:3] == (0, 0, 0):
                r += "A"
            elif px[:3] == (255, 255, 255):
                r += "B"
            else:
                sys.exit(f"{path}: pixel ({x},{y}) is {px}, expected black (outline) or white (fill)")
        rows.append(r)
    return w, h, rows


def render():
    o = []
    w = o.append
    w("/* SPDX-License-Identifier: CC-BY-SA-4.0 */\n")
    w("#ifndef MW_CURSOR_DATA_H\n#define MW_CURSOR_DATA_H\n\n")
    w("/* Auto-generated by tools/gen_cursors.py from third_party/icon-bundle/Images/Cursor/*.png -- the MiniWin icon pack, by\n")
    w(" * SegFault777, licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This file is that artwork in another\n")
    w(" * format, so it stays under that license (see third_party/icon-bundle/NOTICE.md); the rest of the kernel is GPL-3.0-only.\n")
    w(" * Do not hand-edit: change the PNGs and re-run the script.\n")
    w(" *\n")
    w(" * One string per pixel row: '.' transparent, 'A' outline, 'B' fill. The arrow's tip is its top-left pixel (the hot spot);\n")
    w(" * the resize cursors are centred on the pointer. */\n\n")
    for name, png in SHAPES:
        cw, ch, rows = rows_of(os.path.join(SRC, png))
        up = name.upper()
        w(f"#define CURSOR_{up}_W {cw}\n#define CURSOR_{up}_H {ch}\n")
        w(f"static const char *const cursor_{name}[{ch}] = {{\n")
        for r in rows:
            w(f'    "{r}",\n')
        w("};\n\n")
    w("#endif\n")
    return "".join(o)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("kernel/cursor_data.h is out of date -- run tools/gen_cursors.py")
        print("cursor_data.h up to date")
    else:
        open(OUT, "w").write(text)
        print(f"Wrote {OUT}")
