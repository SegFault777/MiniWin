"""Generates docs/dev/SOURCE-MAP.md: one line per source file (boot loader, kernel headers, programs, tools), taken from the first
sentence of the file's own header comment -- so the map can never drift from what the files say about themselves.

    tools/gen_source_map.py            rewrite docs/dev/SOURCE-MAP.md
    tools/gen_source_map.py --check    exit 1 if it is out of date (tools/test/check_docs.py runs this)"""
import os, re, subprocess, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'docs', 'dev', 'SOURCE-MAP.md')
os.chdir(ROOT)

def first_sentence(path):
    try: text = open(path, encoding='utf-8', errors='replace').read()
    except Exception: return ''
    if path.endswith('.asm') or path.endswith('.sh') or path.endswith('.py'):
        lines = []
        for ln in text.split('\n')[:40]:
            if ln.startswith('#!') or 'SPDX' in ln: continue
            m = re.match(r'^\s*[;#]+\s?(.*)$', ln)
            if m and set(m.group(1).strip()) <= set('=-'): continue          # a rule line
            if m: lines.append(m.group(1).strip())
            elif lines: break
        body = ' '.join(l for l in lines if l)
        if not body and path.endswith('.py'):                       # a module docstring instead of comments
            m = re.search(r'"""(.*?)"""', text, re.S)
            body = ' '.join(m.group(1).split()) if m else ''
    else:
        text = re.sub(r'/\*\s*SPDX-License-Identifier[^*]*\*/', '', text, count=1)         # the license line is not a description
        m = re.search(r'/\*(.*?)\*/', text.split('#ifndef', 1)[-1] if '#ifndef' in text[:400] else text, re.S)
        if not m: return ''
        lines = [re.sub(r'^\s*\*+\s?', '', l).strip() for l in m.group(1).split('\n')]
        body = ' '.join(l for l in lines if l and not set(l) <= set('=-*'))
    body = re.sub(r'^[\w./+-]+(\.\w+)?\s+--?\s+', '', body)         # "foo.h -- " prefix
    body = re.sub(r'\s+', ' ', body).strip()
    body = re.sub(r'^=+\s*', '', body)
    cut = re.search(r'(?<=[a-z0-9\)\]`])\.(?:\s|$)', body)
    s = body[:cut.start() + 1] if cut else body
    if len(s) > 190: s = s[:187].rsplit(' ', 1)[0] + '...'
    s = s[:1].upper() + s[1:]
    return s.replace('|', '\\|')

groups = [
    ('Boot loader (`boot/`)', 'boot', ('.asm',)),
    ('Kernel (`kernel/`)', 'kernel', ('.h', '.c', '.asm', '.ld')),
    ('Programs (`programs/`)', 'programs', ('.c', '.h')),
    ('Tools (`tools/`)', 'tools', ('.py', '.sh')),
    ('Tests (`tools/test/`)', 'tools/test', ('.py', '.sh', '.c', '.h')),
]
tracked = [f for f in subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard'], text=True).split('\n') if f]
generated = ('kernel/font_ko_data.h', 'kernel/font_latin_data.h', 'kernel/chain_mbr.h', 'kernel/trusted_roots.h', 'kernel/cursor_data.h')
out = ['# Source map', '',
       'One line per source file, generated by `tools/gen_source_map.py` from the first sentence of each file\'s own header comment',
       '(so it cannot drift: change the comment, re-run the script). Files marked *generated* are produced by a tool and not edited by hand.',
       'For how the pieces fit together see [ARCHITECTURE.md](ARCHITECTURE.md); for the memory layout [MEMORY-MAP.md](MEMORY-MAP.md).', '']
for title, folder, exts in groups:
    files = sorted(f for f in tracked if os.path.dirname(f) == folder and f.endswith(exts) and os.path.exists(f))
    if folder == 'kernel':
        sub = sorted(f for f in tracked if f.startswith('kernel/') and os.path.dirname(f) != 'kernel' and f.endswith(exts) and os.path.exists(f))
        files += sub
    if not files: continue
    out += ['## ' + title, '', '| file | what it is |', '|---|---|']
    for f in files:
        d = first_sentence(f)
        if f in generated: d = ('*generated* -- ' + d) if d else '*generated*'
        out.append('| `%s` | %s |' % (f, d or ''))
    out.append('')
text = '\n'.join(out)
if '--check' in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ''
    if cur != text: sys.exit('docs/dev/SOURCE-MAP.md is out of date -- run tools/gen_source_map.py')
    print('SOURCE-MAP.md up to date')
else:
    open(OUT, 'w').write(text)
    print('wrote', OUT, '(%d files)' % sum(1 for l in out if l.startswith('| `')))
