"""tools/gen_chain_mbr.py <chain_mbr.bin> <out.h> -- turns the assembled boot/chain_mbr.asm (446 bytes) into a C
array the kernel can embed (kernel/chain_mbr.h). build.sh runs this on every build, so the header can never drift
from the assembly; it is committed anyway so the host tests and a fresh checkout can use it without nasm."""
import sys

data = open(sys.argv[1], "rb").read()
if len(data) != 446:
    sys.exit("chain_mbr.bin must be exactly 446 bytes, got %d" % len(data))
rows = []
for i in range(0, len(data), 16):
    rows.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
text = """/* SPDX-License-Identifier: GPL-3.0-only */
#ifndef CHAIN_MBR_H
#define CHAIN_MBR_H
/* GENERATED by tools/gen_chain_mbr.py from boot/chain_mbr.asm -- do not edit by hand (build.sh regenerates it). */
#define CHAIN_MBR_SIZE 446
static const unsigned char chain_mbr_code[CHAIN_MBR_SIZE] = {
%s
};
#endif
""" % "\n".join(rows)
try:
    if open(sys.argv[2]).read() == text:
        sys.exit(0)          # unchanged: leave the file (and its timestamp) alone
except FileNotFoundError:
    pass
open(sys.argv[2], "w").write(text)
